export function widgetQueryAnswer(query, random = Math.random) {
  if (query?.chat?.type !== 'private') return 'Этот виджет работает только в личном чате с Жужей.';
  const replies = WIDGET_REPLIES[query.data];
  if (!replies) return 'Жужа пока не понял этот жест. Попробуй ещё раз 🤗';
  return replies[Math.floor(random() * replies.length)];
}
