def build_catalog() -> tuple[str, ...]:
    messages = ["Желаю тебе манной каши без единого комочка. ✨"]
    for wish_index, wish in enumerate(WISHES):
        for bonus_index, bonus in enumerate(BONUSES):
            template = TEMPLATES[(wish_index + bonus_index) % len(TEMPLATES)]
            messages.append(template.format(wish=wish, bonus=bonus))
    random.Random(20260906).shuffle(messages)
    return tuple(messages)


